#!/usr/bin/env python3
"""Builds lib/app/layouts/settings/settings_search_index.g.dart: every option title (with its
subtitle) and section heading on the Settings pages, for the search field on the Settings page.
Run after adding or renaming settings:  python3 tool/gen_settings_search_index.py"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAGES = "lib/app/layouts/settings/pages/"
# page id -> (file, page name shown in results)
PANELS = {
    "profile": ("profile/profile_panel.dart", "Profile"),
    "status": ("system/status_panel.dart", "Status"),
    "server": ("server/server_management_panel.dart", "Connection & Server"),
    "scheduled": ("scheduling/scheduled_messages_panel.dart", "Scheduled Messages"),
    "reminders": ("scheduling/message_reminders_panel.dart", "Message Reminders"),
    "device": ("system/device_panel.dart", "Device"),
    "theming": ("theming/theming_panel.dart", "Appearance"),
    "media": ("message_view/attachment_panel.dart", "Media"),
    "notifications": ("system/notification_panel.dart", "Notifications"),
    "chatList": ("conversation_list/chat_list_panel.dart", "Chat List"),
    "conversation": ("message_view/conversation_panel.dart", "Conversations"),
    "desktop": ("desktop/desktop_panel.dart", "Desktop"),
    "misc": ("misc/misc_panel.dart", "More Settings"),
    "privateApi": ("advanced/private_api_panel.dart", "Private API Features"),
    "redacted": ("advanced/redacted_mode_panel.dart", "Redacted Mode"),
    "tasker": ("advanced/tasker_panel.dart", "Tasker Integration"),
    "notificationProviders": ("advanced/notification_providers_panel.dart", "Notification Providers"),
    "troubleshoot": ("misc/troubleshoot_panel.dart", "Developer Tools"),
    "backup": ("server/backup_restore_panel.dart", "Backup & Restore"),
    "about": ("misc/about_panel.dart", "About"),
    "passwords": ("passwords/passwords_panel.dart", "Passwords"),
    "browserExtension": ("passwords/browser_extension_panel.dart", "Passwords > Browser Extension"),
}

# words people search for that the options don't say themselves: (page, title or None for the page)
KEYWORDS = {
    ("theming", None): "look style design",
    ("theming", "App Theme"): "dark mode light mode night mode color scheme theme",
    ("theming", "Text and Font"): "font size text size",
    ("notifications", None): "alerts sounds banners notify",
    ("chatList", None): "conversation list inbox home",
    ("chatList", "Swipe Actions"): "gestures swipe",
    ("chatList", "Pinned Order"): "pins pinned chats",
    ("conversation", None): "messages chat typing bubbles",
    ("media", None): "attachments photos pictures images videos downloads",
    ("passwords", None): "keychain logins credentials passkeys wifi codes 2fa",
    ("browserExtension", None): "chrome edge firefox autofill extension fill",
    ("status", None): "health connection relay mac registration problems",
    ("troubleshoot", None): "logs debug developer bugs",
    ("about", None): "version licenses source code",
    ("profile", None): "account apple id phone number aliases",
    ("backup", None): "export import restore",
    ("desktop", None): "windows tray startup launch close",
}

STRING = r'"((?:[^"\\]|\\.)*)"'
TITLE = re.compile(r'\btitle:\s*' + STRING)
SUBTITLE = re.compile(r'\bsubtitle:\s*' + STRING)
HEADER = re.compile(r'SettingsHeader\((?:[^()]|\([^()]*\))*?\btext:\s*' + STRING, re.S)

def clean(s):
    s = s.replace('\\"', '"').replace("\\n", " ").replace("\\'", "'")
    return re.sub(r"\s+", " ", s).strip()

entries = []
for page, (path, name) in PANELS.items():
    src = open(os.path.join(ROOT, PAGES, path), encoding="utf-8").read()
    seen = {name.lower()}
    entries.append({"page": page, "title": name, "subtitle": "", "section": True, "keywords": KEYWORDS.get((page, None), "")})
    for m in HEADER.finditer(src):
        text = clean(m.group(1))
        if "$" in text or not text or text.lower() in seen: continue
        seen.add(text.lower())
        entries.append({"page": page, "title": text, "subtitle": "", "section": True, "keywords": KEYWORDS.get((page, text), "")})
    for m in TITLE.finditer(src):
        title = clean(m.group(1))
        if "$" in title or len(title) < 3 or title.lower() in seen: continue
        seen.add(title.lower())
        # the subtitle that belongs to this tile: before the next title
        rest = src[m.end():]
        nxt = TITLE.search(rest)
        window = rest[: nxt.start() if nxt else 600][:600]
        sub = SUBTITLE.search(window)
        subtitle = clean(sub.group(1)) if sub and "$" not in sub.group(1) else ""
        entries.append({"page": page, "title": title, "subtitle": subtitle, "section": False, "keywords": KEYWORDS.get((page, title), "")})

def dart(s):
    return json.dumps(s, ensure_ascii=False).replace("$", "\\$")

out = ["// GENERATED by tool/gen_settings_search_index.py. Do not edit by hand.", "",
       "class SettingsSearchEntry {",
       "  const SettingsSearchEntry(this.page, this.title, this.subtitle, this.section, [this.keywords = \"\"]);",
       "  final String page;", "  final String title;", "  final String subtitle;",
       "  /// other words that should find this entry (not shown)", "  final String keywords;",
       "  /// a page or section heading rather than a single option", "  final bool section;", "}", "",
       "const settingsPageNames = <String, String>{"]
for page, (_, name) in PANELS.items():
    out.append(f"  {dart(page)}: {dart(name)},")
out += ["};", "", "const settingsSearchIndex = <SettingsSearchEntry>["]
for e in entries:
    kw = f", {dart(e['keywords'])}" if e['keywords'] else ""
    out.append(f"  SettingsSearchEntry({dart(e['page'])}, {dart(e['title'])}, {dart(e['subtitle'])}, {'true' if e['section'] else 'false'}{kw}),")
out += ["];", ""]
open(os.path.join(ROOT, "lib/app/layouts/settings/settings_search_index.g.dart"), "w", encoding="utf-8").write("\n".join(out))
print(len(entries), "entries")
